CREATE   PROCEDURE [dbo].[sp_ObtenerCarrito]
    @UsuarioID INT
AS
BEGIN
    SET NOCOUNT ON;
    SELECT
        c.CarritoID, c.ProductoID, p.Nombre, p.PrecioVenta, c.Cantidad,
        c.TallaSeleccionada, c.ColorSeleccionado,
        (p.PrecioVenta * c.Cantidad) AS Subtotal,
        p.ImagenPrincipal, c.FechaAgregado
    FROM Carrito c
    INNER JOIN Productos p ON c.ProductoID = p.ProductoID
    WHERE c.UsuarioID = @UsuarioID
    ORDER BY c.FechaAgregado DESC;

    SELECT SUM(p.PrecioVenta * c.Cantidad) AS Total
    FROM Carrito c
    INNER JOIN Productos p ON c.ProductoID = p.ProductoID
    WHERE c.UsuarioID = @UsuarioID;
END;
