CREATE   PROCEDURE [dbo].[sp_CrearPedido]
    @ClienteID INT,
    @NombreCliente NVARCHAR(100),
    @EmailCliente NVARCHAR(100),
    @TelefonoCliente NVARCHAR(20),
    @DireccionEnvio NVARCHAR(255),
    @Ciudad NVARCHAR(100),
    @MetodoPago NVARCHAR(50),
    @Descuento DECIMAL(18,2) = 0,
    @Envio DECIMAL(18,2) = 0,
    @Notas NVARCHAR(MAX) = NULL,
    @PedidoID INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRANSACTION;
    BEGIN TRY
        DECLARE @Subtotal DECIMAL(18,2);
        SELECT @Subtotal = ISNULL(SUM(c.Cantidad * p.PrecioVenta), 0)
        FROM Carrito c
        INNER JOIN Productos p ON c.ProductoID = p.ProductoID
        WHERE c.UsuarioID = @ClienteID;

        DECLARE @Total DECIMAL(18,2) = @Subtotal - @Descuento + @Envio;

        INSERT INTO Pedidos (
            ClienteID, NombreCliente, EmailCliente, TelefonoCliente,
            DireccionEnvio, Ciudad, MetodoPago,
            Subtotal, Descuento, Envio, Total, Notas
        )
        VALUES (
            @ClienteID, @NombreCliente, @EmailCliente, @TelefonoCliente,
            @DireccionEnvio, @Ciudad, @MetodoPago,
            @Subtotal, @Descuento, @Envio, @Total, @Notas
        );
        SET @PedidoID = SCOPE_IDENTITY();

        INSERT INTO PedidoDetalles (
            PedidoID, ProductoID, TallaID, ColorID,
            Cantidad, PrecioUnitario, Subtotal
        )
        SELECT
            @PedidoID, c.ProductoID, NULL, NULL,
            c.Cantidad, p.PrecioVenta, c.Cantidad * p.PrecioVenta
        FROM Carrito c
        INNER JOIN Productos p ON c.ProductoID = p.ProductoID
        WHERE c.UsuarioID = @ClienteID;

        UPDATE Productos
        SET Stock = Stock - c.Cantidad
        FROM Productos p
        INNER JOIN Carrito c ON p.ProductoID = c.ProductoID
        WHERE c.UsuarioID = @ClienteID;

        DELETE FROM Carrito WHERE UsuarioID = @ClienteID;

        INSERT INTO Ventas (
            ClienteID, FechaVenta, Subtotal, Descuento, Envio, Total, Estado, MetodoPago
        )
        VALUES (
            @ClienteID, GETDATE(), @Subtotal, @Descuento, @Envio, @Total, 'Completada', @MetodoPago
        );

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        ROLLBACK TRANSACTION;
        RAISERROR('Error al crear pedido', 16, 1);
    END CATCH
END;
GO
