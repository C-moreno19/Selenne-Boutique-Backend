CREATE   PROCEDURE [dbo].[sp_ResetPassword]
    @Token NVARCHAR(500),
    @NewPasswordHash NVARCHAR(255),
    @Success BIT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET @Success = 0;
    BEGIN TRANSACTION;
    BEGIN TRY
        DECLARE @UsuarioID INT = (
            SELECT TOP 1 UsuarioID FROM PasswordResetTokens
            WHERE Token = @Token AND ExpiresAt >= GETDATE() AND Used = 0
        );
        IF @UsuarioID IS NULL
        BEGIN
            RAISERROR('Token invalido o expirado', 16, 1);
            RETURN;
        END
        UPDATE Usuarios SET PasswordHash = @NewPasswordHash WHERE UsuarioID = @UsuarioID;
        UPDATE PasswordResetTokens SET Used = 1, UsedAt = GETDATE() WHERE Token = @Token;
        EXEC sp_RevokeAllUserTokens @UsuarioID;
        SET @Success = 1;
        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        ROLLBACK TRANSACTION;
        RAISERROR('Error al resetear contrasena', 16, 1);
    END CATCH
END;
GO
