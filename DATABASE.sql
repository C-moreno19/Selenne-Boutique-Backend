CREATE   PROCEDURE [dbo].[sp_ActualizarEstadoPedido]
    @PedidoID INT,
    @NuevoEstado NVARCHAR(20),
    @Notas NVARCHAR(MAX) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRANSACTION;
    BEGIN TRY
        DECLARE @EstadoAnterior NVARCHAR(20);
        DECLARE @ClienteID INT;
        SELECT @EstadoAnterior = Estado, @ClienteID = ClienteID
        FROM Pedidos WHERE PedidoID = @PedidoID;

        UPDATE Pedidos
        SET Estado = @NuevoEstado,
            Notas = ISNULL(@Notas, Notas),
            FechaActualizacion = GETDATE()
        WHERE PedidoID = @PedidoID;

        INSERT INTO AuditoriaPerfil (
            UsuarioID, TipoCambio, CampoModificado, ValorAnterior, ValorNuevo, Origen
        )
        VALUES (
            @ClienteID, 'pedido', 'Estado', @EstadoAnterior, @NuevoEstado, 'sistema'
        );

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        ROLLBACK TRANSACTION;
        RAISERROR('Error al actualizar pedido', 16, 1);
    END CATCH
END;
